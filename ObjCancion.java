public class ObjCancion {
    String Titulo;
    String Cantante;
    int Año;
    
    public ObjCancion() {
    }

    public String getTitulo() {
        return Titulo;
    }

    public void setTitulo(String titulo) {
        Titulo = titulo;
    }

    public String getCantante() {
        return Cantante;
    }

    public void setCantante(String cantante) {
        Cantante = cantante;
    }

    public int getAño() {
        return Año;
    }

    public void setAño(int año) {
        Año = año;
    }

    
}
